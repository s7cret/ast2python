@pytest.mark.parametrize("version", [5, 6])
@pytest.mark.parametrize("private_kind", ["function", "method"])
def test_private_more_specific_candidate_does_not_capture_export(version, private_kind):
    method = "method " if private_kind == "method" else ""
    other = "method " if private_kind == "function" else ""
    decl = f"{method}f(int x)=>x+100\nexport {other}f(float x)=>x+1\nexport g(int x)=>f(x)"
    c, _ = compile_linked(
        script("plot(lib.f(2))\nplot(lib.g(2))", version=version),
        {"user/Lib/1": library(decl, version=version)},
    )
    rt, cls = runtime_for(c)
    assert advance(rt, cls, [1, 2]) == [3.0, 102] * 2


@pytest.mark.parametrize("version", [5, 6])
def test_namespaces_with_separate_function_and_method_do_not_compete(version):
    libs = {
        "u/A/1": library("export f(string x)=>str.length(x)", "A", version),
        "u/B/1": library("export method f(int self)=>self+10", "B", version),
    }
    c, _ = compile_linked(
        script(
            'plot(a.f("abc"))\nplot(b.f(2))',
            imports="import u/A/1 as a\nimport u/B/1 as b",
            version=version,
        ),
        libs,
    )
    rt, cls = runtime_for(c)
    assert advance(rt, cls, [1, 2]) == [3, 12] * 2


@pytest.mark.parametrize("version", [5, 6])
def test_transitive_mixed_exports_remain_private_to_direct_import_scope(version):
    from pine2ast.libraries import LibraryError

    libs = {
        "u/Dep/1": library(
            "export f(string x)=>str.length(x)\nexport method f(int self)=>self+1", "Dep", version
        ),
        "user/Lib/1": library(
            "import u/Dep/1 as dep\nexport g(int x)=>dep.f(x)\nexport g(string x)=>dep.f(x)",
            version=version,
        ),
    }
    c, _ = compile_linked(script('plot(lib.g(2))\nplot(lib.g("abcd"))', version=version), libs)
    rt, cls = runtime_for(c)
    assert advance(rt, cls, [1]) == [3, 4]
    for bad in ["plot(lib.f(2))", "x=2\nplot(x.f())", "plot(dep.f(2))"]:
        with pytest.raises((LibraryError, ValueError)):
            compile_linked(script(bad, version=version), libs)


@pytest.mark.parametrize("version", [5, 6])
@pytest.mark.parametrize("imported", [False, True])
def test_sma_parameter_context_history_and_inputs_do_not_mix(version, imported):
    ns = "lib." if imported else ""
    decl = "export f(string x)=>str.length(x)\nexport method f(float self,simple int n)=>ta.sma(self,n)"
    c = compile_family(
        decl, f'n=input.int(2)\nplot({ns}f(close,n))\nplot({ns}f("abc"))', version, imported
    )
    for length in (2, 3):
        rt, cls = runtime_for(c, {"n": length})
        out = advance(rt, cls, [1, 2, 3])
        assert out[1::2] == [3] * 3
        assert all(is_na(x) for x in out[0 : 2 * (length - 1) : 2])
        assert out[2 * (length - 1) :: 2] == ([1.5, 2.5] if length == 2 else [2])
